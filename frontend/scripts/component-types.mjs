import { readFileSync, writeFileSync } from 'node:fs'
import { basic, groups } from './ant-components.mjs'

// Deterministic types must exist before vue-tsc, including on a clean checkout.
// These are erased type imports; runtime imports still use the direct resolver.
const names = [...new Set([...basic, ...Object.keys(groups)])].sort()
const source = `// Generated by scripts/component-types.mjs. Runtime imports are separate.
export {}
declare module 'vue' {
  export interface GlobalComponents {
${names.map(name => `    A${name}: typeof import('ant-design-vue/es')['${name}']`).join('\n')}
    RouterLink: typeof import('vue-router')['RouterLink']
    RouterView: typeof import('vue-router')['RouterView']
  }
}
`
const target = 'src/components.d.ts'
let previous = ''
try { previous = readFileSync(target,'utf8') } catch { /* First clean build. */ }
if (previous !== source) writeFileSync(target, source)
